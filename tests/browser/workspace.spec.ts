import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('branded walkthrough: requests, drafts, division lens and offline persistence',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Open sample walkthrough'}).click();
 await expect(page.getByRole('heading',{name:'Your working day'})).toBeVisible();
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 await expect(page.getByText('Decision recorded.')).toBeVisible();
 await page.getByRole('button',{name:'Request leave',exact:true}).click();
 await page.getByLabel('Title', {exact:true}).fill('December leave');
 await page.getByLabel('First day').fill('2026-12-14');await page.getByLabel('Last day').fill('2026-12-16');
 await page.getByLabel('Details',{exact:true}).fill('Cover arranged with the project lead.');
 await page.getByRole('button',{name:'Close draft'}).click();await page.getByRole('button',{name:'Request leave',exact:true}).click();
 await expect(page.getByLabel('Title',{exact:true})).toHaveValue('December leave');
 await page.getByRole('button',{name:'Submit',exact:true}).click();await expect(page.getByText('December leave',{exact:true})).toBeVisible();
 await page.getByRole('radio',{name:'Asset Management',exact:true}).click();await expect(page.getByText('December leave',{exact:true})).toHaveCount(0);
 await page.getByRole('radio',{name:'Both',exact:true}).click();
 await page.keyboard.press('Control+k');await expect(page.getByRole('dialog')).toBeVisible();await page.getByLabel('Find a page or action').fill('Projects');
 await page.getByRole('dialog').getByRole('button',{name:'Projects Go to'}).click();await expect(page.getByText('Kampala infrastructure survey')).toBeVisible();
 await page.getByRole('button',{name:'Field reports',exact:true}).click();
 await context.setOffline(true);await page.getByLabel('What happened on site?').fill('Site note while disconnected');await page.getByRole('button',{name:'Save on this device'}).click();
 await expect(page.getByRole('button',{name:/1 on this phone/})).toBeVisible();
 await context.setOffline(false);await expect(page.getByRole('button',{name:'✓ Saved',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Inbox',exact:true}).first().click();
 await page.screenshot({path:'.validation/workspace-desktop.png',fullPage:true});
 const axe=await new AxeBuilder({page}).analyze();expect(axe.violations.filter(v=>['critical','serious'].includes(v.impact||''))).toEqual([]);
 expect(errors).toEqual([]);
});
test('mobile and dark themes fit narrow viewports',async({page})=>{
 await page.setViewportSize({width:375,height:812});await page.goto('/');await page.getByRole('button',{name:'Open sample walkthrough'}).click();
 await page.getByRole('button',{name:'Use dark theme'}).click();
 await expect(page.getByRole('heading',{name:'Your working day'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 const axe=await new AxeBuilder({page}).analyze();expect(axe.violations.filter(v=>['critical','serious'].includes(v.impact||''))).toEqual([]);
 await page.screenshot({path:'.validation/workspace-mobile-dark.png',fullPage:true});
 await page.setViewportSize({width:320,height:720});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
